export function seedBrandKnowledge(): BrandKnowledgeEntry[] {
  return SEED_BRAND_KNOWLEDGE.map((item) => ({ ...item, restrictedTerms: item.restrictedTerms ? [...item.restrictedTerms] : undefined, tags: item.tags ? [...item.tags] : undefined }))
}

export function createBrandKnowledgeEntry(input: Omit<BrandKnowledgeEntry, 'id' | 'createdAt' | 'updatedAt'>): BrandKnowledgeEntry {
  const timestamp = new Date().toISOString()
  return {
    ...input,
    id: `bk${Date.now()}`,
    createdAt: timestamp,
    updatedAt: timestamp,
  }
}