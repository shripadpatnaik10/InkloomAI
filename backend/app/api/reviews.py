from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.db.session import get_db
from app.models.models import ApprovedFact, BrandRule, ContentItem, ContentRevision, Finding, FindingStatus, Review
from app.schemas.schemas import CorrectionRead, CorrectionRequest, FindingRead, ReviewCreate, ReviewRead
from app.services.brand_analysis_service import BrandAnalysisService

router = APIRouter(prefix="/api/v1", tags=["reviews"])

@router.post("/content/{content_id}/reviews", response_model=ReviewRead, status_code=201)
def create_review(content_id: str, payload: ReviewCreate, db: Session = Depends(get_db)):
    item = db.get(ContentItem, content_id)
    if not item:
        raise HTTPException(status_code=404, detail="Content not found")
    revision = db.query(ContentRevision).filter_by(content_item_id=content_id).order_by(ContentRevision.revision_number.desc()).first()
    if not revision:
        raise HTTPException(status_code=400, detail="Content has no revision")
    rules = db.query(BrandRule).all()
    facts = db.query(ApprovedFact).all()
    result = BrandAnalysisService(item.current_content, rules, facts).run()
    review = Review(
        content_item_id=content_id,
        content_revision_id=revision.id,
        analysis_type="simulated",
        analysis_mode=result["mode"],
        model_name=result["model_name"],
        request_id=result["request_id"],
        score=result["score"],
        status="completed",
        created_by_id=payload.created_by,
    )
    db.add(review)
    db.flush()
    for finding in result["findings"]:
        db.add(Finding(review_id=review.id, **finding))
    db.commit()
    db.refresh(review)
    return review

@router.get("/reviews", response_model=list[ReviewRead])
def list_reviews(db: Session = Depends(get_db)):
    return db.query(Review).order_by(Review.analyzed_at.desc()).all()

@router.get("/reviews/{review_id}", response_model=ReviewRead)
def get_review(review_id: str, db: Session = Depends(get_db)):
    review = db.get(Review, review_id)
    if not review:
        raise HTTPException(status_code=404, detail="Review not found")
    return review

@router.patch("/findings/{finding_id}", response_model=FindingRead)
def update_finding(finding_id: str, status: FindingStatus, db: Session = Depends(get_db)):
    finding = db.get(Finding, finding_id)
    if not finding:
        raise HTTPException(status_code=404, detail="Finding not found")
    finding.status = status
    db.commit()
    db.refresh(finding)
    return finding

@router.post("/reviews/{review_id}/findings/{finding_id}/suggest-correction", response_model=CorrectionRead)
def suggest_correction(review_id: str, finding_id: str, payload: CorrectionRequest, db: Session = Depends(get_db)):
    review = db.get(Review, review_id)
    if not review:
        raise HTTPException(status_code=404, detail="Review not found")
    finding = db.get(Finding, finding_id)
    if not finding or finding.review_id != review_id:
        raise HTTPException(status_code=404, detail="Finding not found")
    from app.models.models import BrandRule
    rule = db.get(BrandRule, finding.brand_rule_id) if finding.brand_rule_id else None
    from app.services.ai.factory import get_ai_provider
    provider = get_ai_provider()
    if provider is None:
        return CorrectionRead(suggested_correction=payload.original_excerpt, rationale="AI is disabled or not configured. No AI suggestion available.")
    from app.services.ai.prompt_builder import PromptBuilder
    system, user = PromptBuilder.build_correction_prompt(payload.original_excerpt, rule, payload.suggested_context or "")
    suggestion = provider.suggest_correction(system, user)
    return CorrectionRead(suggested_correction=suggestion or payload.original_excerpt, rationale="Generated by configured AI provider.")